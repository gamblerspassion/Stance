import {chromium} from 'playwright';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1280,height:850}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const uri=pathToFileURL(resolve(process.env.GITHUB_WORKSPACE,'signal-evidence/SIGNAL-interactive-preview.html')).href;
await page.goto(uri,{waitUntil:'domcontentloaded',timeout:60000});
await page.locator('#results h2').getByText(/45202/).waitFor({timeout:30000});
await page.locator('.leaflet-container').waitFor({timeout:20000});
await page.locator('#boundarystatus').getByText(/Official Census 2020 ZCTA 45202 polygon rendered/).waitFor({timeout:30000});
if(await page.locator('#map path.leaflet-interactive').count()<1)throw Error('Standalone 45202 boundary did not render');
await page.locator('[data-zip="32303"]').click();
await page.locator('#results h2').getByText(/32303/).waitFor({timeout:15000});
await page.locator('#boundarystatus').getByText(/Official Census 2020 ZCTA 32303 polygon rendered/).waitFor({timeout:25000});
await page.locator('[data-zip="98004"]').click();
await page.locator('#boundarystatus').getByText(/Official Census 2020 ZCTA 98004 polygon rendered/).waitFor({timeout:25000});
await page.locator('[data-zip="00601"]').click();
await page.locator('#boundarystatus').getByText(/Official Census 2020 ZCTA 00601 polygon rendered/).waitFor({timeout:25000});
await page.locator('#input').fill('99999');await page.locator('#search button').click();
await page.locator('#results').getByText(/not represented/).waitFor({timeout:15000});
if(errors.length)throw Error('Console exceptions: '+errors.join('; '));
const result={passed:true,marketRecords:41721,polygonZips:['45202','32303','98004','00601'],unknownZip:'handled',javascriptErrors:0};
await writeFile(resolve(process.env.GITHUB_WORKSPACE,'signal-evidence/standalone-html-proof.json'),JSON.stringify(result,null,2));
console.log('STANDALONE_HTML_PROOF',JSON.stringify(result));
await browser.close();
